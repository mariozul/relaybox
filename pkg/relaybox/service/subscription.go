// Package service implements application business logic (RULE-ARCH-01).
// Services orchestrate domain entities and repository interfaces without
// importing HTTP frameworks, database drivers, or infrastructure details.
package service

import (
	"context"
	"time"

	"github.com/mariozul/relaybox/pkg/relaybox/domain"
	"github.com/mariozul/relaybox/pkg/relaybox/dto"
	"github.com/mariozul/relaybox/pkg/relaybox/repository"
)

// SubscriptionService manages webhook subscriber registrations (FR-SUB-01).
// All operations are scoped to the requesting tenant (FR-SUB-02, RULE-SEC-01).
type SubscriptionService interface {
	// CreateSubscription creates a new subscription for the given tenant.
	// Returns the subscription ID or an error.
	CreateSubscription(ctx context.Context, tenantID string, req *dto.CreateSubscriptionRequest) (string, error)

	// GetSubscription retrieves a single subscription scoped to the tenant.
	// Returns domain.ErrSubscriptionNotFound if the subscription does not exist
	// or if the tenant does not own it (FR-SUB-02).
	GetSubscription(ctx context.Context, tenantID, id string) (*domain.Subscription, error)

	// ListSubscriptions returns all subscriptions belonging to the tenant (FR-SUB-02).
	ListSubscriptions(ctx context.Context, tenantID string) ([]domain.Subscription, error)

	// UpdateSubscription modifies an existing subscription.
	// Returns domain.ErrSubscriptionNotFound if the subscription does not exist
	// or if the tenant does not own it (FR-SUB-02).
	UpdateSubscription(ctx context.Context, tenantID, id string, req *dto.UpdateSubscriptionRequest) error

	// DeleteSubscription removes a subscription.
	// Returns domain.ErrSubscriptionNotFound if the subscription does not exist
	// or if the tenant does not own it (FR-SUB-02).
	DeleteSubscription(ctx context.Context, tenantID, id string) error
}

// subscriptionService implements SubscriptionService.
type subscriptionService struct {
	subRepo repository.SubscriptionRepository
	clock   func() time.Time
}

// NewSubscriptionService creates a new SubscriptionService.
func NewSubscriptionService(subRepo repository.SubscriptionRepository, clock func() time.Time) SubscriptionService {
	return &subscriptionService{
		subRepo: subRepo,
		clock:   clock,
	}
}

// CreateSubscription creates a new subscription (FR-SUB-01).
func (s *subscriptionService) CreateSubscription(ctx context.Context, tenantID string, req *dto.CreateSubscriptionRequest) (string, error) {
	if tenantID == "" {
		return "", domain.ErrUnauthorized
	}
	if req.EventType == "" || req.TargetURL == "" {
		return "", domain.ErrInvalidInput
	}

	now := s.clock()
	sub := &domain.Subscription{
		ID:        "",      // will be generated by the repository
		TenantID:  tenantID,
		EventType: req.EventType,
		TargetURL: req.TargetURL,
		CreatedAt: now,
		CreatedBy: tenantID,
		UpdatedAt: now,
		UpdatedBy: tenantID,
	}

	id, err := s.subRepo.CreateSubscription(ctx, sub)
	if err != nil {
		return "", err
	}
	return id, nil
}

// GetSubscription retrieves a subscription scoped to the tenant (FR-SUB-02).
func (s *subscriptionService) GetSubscription(ctx context.Context, tenantID, id string) (*domain.Subscription, error) {
	if tenantID == "" {
		return nil, domain.ErrUnauthorized
	}
	if id == "" {
		return nil, domain.ErrInvalidInput
	}

	sub, err := s.subRepo.GetSubscriptionByID(ctx, tenantID, id)
	if err != nil {
		return nil, err
	}
	if sub == nil {
		return nil, domain.ErrSubscriptionNotFound
	}
	return sub, nil
}

// ListSubscriptions returns all subscriptions for the tenant (FR-SUB-02).
func (s *subscriptionService) ListSubscriptions(ctx context.Context, tenantID string) ([]domain.Subscription, error) {
	if tenantID == "" {
		return nil, domain.ErrUnauthorized
	}

	subs, err := s.subRepo.ListSubscriptions(ctx, tenantID)
	if err != nil {
		return nil, err
	}
	return subs, nil
}

// UpdateSubscription modifies an existing subscription (FR-SUB-01, FR-SUB-02).
func (s *subscriptionService) UpdateSubscription(ctx context.Context, tenantID, id string, req *dto.UpdateSubscriptionRequest) error {
	if tenantID == "" {
		return domain.ErrUnauthorized
	}
	if id == "" {
		return domain.ErrInvalidInput
	}
	if req.EventType == nil && req.TargetURL == nil {
		return domain.ErrInvalidInput
	}

	// Fetch existing subscription to ensure it belongs to the tenant (FR-SUB-02)
	existing, err := s.subRepo.GetSubscriptionByID(ctx, tenantID, id)
	if err != nil {
		return err
	}
	if existing == nil {
		return domain.ErrSubscriptionNotFound
	}

	// Apply updates
	now := s.clock()
	if req.EventType != nil {
		existing.EventType = *req.EventType
	}
	if req.TargetURL != nil {
		existing.TargetURL = *req.TargetURL
	}
	existing.UpdatedAt = now
	existing.UpdatedBy = tenantID

	return s.subRepo.UpdateSubscription(ctx, existing)
}

// DeleteSubscription removes a subscription (FR-SUB-01, FR-SUB-02).
func (s *subscriptionService) DeleteSubscription(ctx context.Context, tenantID, id string) error {
	if tenantID == "" {
		return domain.ErrUnauthorized
	}
	if id == "" {
		return domain.ErrInvalidInput
	}

	err := s.subRepo.DeleteSubscription(ctx, tenantID, id)
	if err == domain.ErrSubscriptionNotFound {
		return domain.ErrSubscriptionNotFound
	}
	return err
}
